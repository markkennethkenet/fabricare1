import 'dart:convert';
import 'dart:io';
import 'package:hive/hive.dart';
import 'package:path/path.dart' as p;
import '../models/scan_result.dart';

/// Hive keeps nested scan records without native database bindings or adapters.
class HistoryStore {
  final Directory root;
  late Box<String> _box;
  HistoryStore(this.root);

  Future<void> open() async {
    await root.create(recursive: true);
    _box = await Hive.openBox<String>('scan_history',
        path: p.join(root.path, 'database'));
  }

  String _key(String userId, String id) => '$userId:$id';
  List<ScanResult> forUser(String userId) => _box.values
      .map((s) => ScanResult.fromJson(jsonDecode(s) as Map<String, dynamic>))
      .where((s) => s.userId == userId)
      .toList()
    ..sort((a, b) => b.dateScanned.compareTo(a.dateScanned));

  Future<ScanResult> add(ScanResult scan) async {
    // Numeric account/scan IDs are generated by the existing auth API and client.
    if (!RegExp(r'^\d+$').hasMatch(scan.userId) ||
        !RegExp(r'^\d+$').hasMatch(scan.id)) {
      throw ArgumentError('Invalid account or scan ID');
    }
    final directory =
        Directory(p.join(root.path, 'scan_media', scan.userId, scan.id));
    await directory.create(recursive: true);
    try {
      final images = <ScanImage>[];
      for (var i = 0; i < scan.images.length; i++) {
        final source = scan.images[i];
        final target = p.join(directory.path, '$i${p.extension(source.path)}');
        await source.file.copy(target);
        images.add(ScanImage(view: source.view, path: target));
      }
      final saved = scan.withImages(images);
      await put(saved);
      return saved;
    } catch (_) {
      await directory.delete(recursive: true);
      rethrow;
    }
  }

  Future<void> put(ScanResult scan) =>
      _box.put(_key(scan.userId, scan.id), jsonEncode(scan.toJson()));

  Future<void> delete(String userId, String id) async {
    final key = _key(userId, id);
    final raw = _box.get(key);
    if (raw == null) return;
    final scan = ScanResult.fromJson(jsonDecode(raw) as Map<String, dynamic>);
    final mediaRoot = p.normalize(p.absolute(p.join(root.path, 'scan_media')));
    for (final image in scan.images) {
      final imagePath = p.normalize(p.absolute(image.path));
      if (p.isWithin(mediaRoot, imagePath) && await File(imagePath).exists()) {
        await File(imagePath).delete();
      }
    }
    await _box.delete(key);
  }

  Future<void> clear(String userId) async {
    for (final scan in forUser(userId)) {
      await delete(userId, scan.id);
    }
  }

  Future<void> close() => _box.close();
}
